-- SHILPA LMS Baseline Database Schema
-- Captured from legacy application audit

CREATE TABLE IF NOT EXISTS `users` (
  `UserId` INT AUTO_INCREMENT PRIMARY KEY,
  `Full_Name` VARCHAR(255) NOT NULL,
  `Email` VARCHAR(255) NOT NULL UNIQUE,
  `Password` VARCHAR(255) NOT NULL,
  `user_type` VARCHAR(20) DEFAULT 'student',
  `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `course` (
  `C_ID` INT AUTO_INCREMENT PRIMARY KEY,
  `C_NAME` VARCHAR(255) NOT NULL,
  `C_CARD_DESCRIPTION` TEXT,
  `C_DESCRIPTION` LONGTEXT,
  `C_CARD_IMAGE` VARCHAR(500),
  `C_DONE_BY` VARCHAR(255),
  `C_LINK` VARCHAR(500),
  `TOP_COURSE` VARCHAR(10) DEFAULT 'No',
  `C_ADD_DATE` TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
